#!/usr/bin/env python3
"""Rebuild catalog.toml, the index Noctalia reads to list this source's plugins."""
import subprocess
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIELDS = ("id", "name", "version", "author", "license", "icon", "description", "plugin_api", "tags")


def commit_times(path, *extra):
    """Commit times touching path, newest first; empty before the first commit."""
    res = subprocess.run(["git", "log", *extra, "--format=%ct", "--", str(path)],
                         cwd=ROOT, capture_output=True, text=True)
    return [int(t) for t in res.stdout.split()] if res.returncode == 0 else []


def value(v):
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "[" + ", ".join(value(x) for x in v) + "]"
    return str(v)


# shortcut: one row per plugin, no [[plugin.release]] ladder for older plugin_api; add one if a release ever needs it.
def main():
    rows = ["# Generated by tools/catalog.py. Do not edit by hand.", ""]
    for manifest in sorted(ROOT.glob("*/plugin.toml")):
        meta = tomllib.loads(manifest.read_text())
        rows.append("[[plugin]]")
        for field in FIELDS:
            if field in meta:
                rows.append(f"{field} = {value(meta[field])}")
        times = commit_times(manifest)
        if times:
            rows.append(f"updated_at = {times[0]}")
            rows.append(f"added_at = {times[-1]}")
        rows.append("")
    (ROOT / "catalog.toml").write_text("\n".join(rows))


if __name__ == "__main__":
    main()
